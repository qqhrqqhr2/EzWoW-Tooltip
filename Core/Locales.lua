function LocaleRegistry.resolveActiveLocale()
    local userPref = addon.db and addon.db.general and addon.db.general.language or "auto"
    if not userPref or userPref == "auto" then
        userPref = GetLocale and GetLocale() or "enUS"
        if userPref == "esMX" then userPref = "esES" end
    end
    return userPref
end

function LocaleRegistry.resolveExtraLocaleText(key)
    local userPref = LocaleRegistry.resolveActiveLocale()
    local targetTable = EXTRA_LOCALE[userPref] or EXTRA_LOCALE.enUS
    return targetTable[key] or EXTRA_LOCALE.enUS[key] or key
end

function LocaleRegistry.composeIcon(icon)
    if not icon then return "" end
    return format("|T%s:14:14:0:0:64:64:4:60:4:60|t ", tostring(icon))
end

